<?php

    function calSuma(int $numero1, int $numero2){
        $resultado = $numero1+$numero2;
        return $resultado;
    }

    function calResta(int $numero1, int $numero2){
        $resultado = $numero1-$numero2;
        return $resultado;
    }

    function calMultiplicacion(int $numero1, int $numero2){
        $resultado = $numero1*$numero2;
        return $resultado;
    }

    function calDivision(int $numero1, int $numero2){
        $resultado = $numero1/$numero2;
        return $resultado;
    }

    function calPotencia(int $numero1, int $numero2){
        $resultado = $numero1**$numero2;
        return $resultado;
    }

?>